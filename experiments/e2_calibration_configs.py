"""E2. Which threshold-calibration configuration should ship?

Evaluates the deployed classifier under several calibration configurations, on
every labelled set available, and reports the two error types that matter
separately:

  leak        an off-task window wrongly called ON TASK (a distraction the system misses)
  false alarm a focused window wrongly called OFF TASK (the system interrupts real work)

Configurations (all call the shipped engine.calibrate_threshold(), never a
reimplementation, so what is measured is what runs):

  fixed_0.01              no calibration at all, the pre-August global threshold
  generic                 generic distraction bank only (workspace_samples.json)
  generic_worklike        + work-like distractions bank            <- shipped today
  generic_worklike_pruned + work-like bank with self-defeating examples removed
  generic_hardneg         + generated goal-specific hard negatives (the rejected experiment)
  worklike_pruned_hardneg + pruned work-like bank and hard negatives

The pruning rule, decided on principle rather than by looking at which goals
scored badly: a calibration example must never name something a user could
plausibly declare as their own session goal. A CV, a household budget or a
council tax login can each be someone's actual task, so teaching the system
that those windows are distractions raises the bar above that user's real work.
Ambient application chrome (an inbox, a calendar, Finder, System Settings) is
never a declared goal, so it stays.

Datasets (each used only if present):
  data/workspace_dumps/evaluation_set.json          6 goals, 144 samples (in sample)
  data/workspace_dumps/evaluation_set_holdout.json  3 goals, 72 samples (held out)
  data/label_audit/heldout_set_labelled.json        6 goals, 120 samples, human-labelled

Output: results/final_eval/e2_calibration.json
Usage:  python experiments/e2_calibration_configs.py       (about 4 min)
"""
import json
import os
import tempfile

from _common import ROOT, banner, run_meta, save_json

EVAL_SETS = [
    ("in_sample", os.path.join(ROOT, "data", "workspace_dumps", "evaluation_set.json")),
    ("held_out", os.path.join(ROOT, "data", "workspace_dumps", "evaluation_set_holdout.json")),
    ("label_audited", os.path.join(ROOT, "data", "label_audit", "heldout_set_labelled.json")),
]

# Work-like calibration examples that could themselves be a user's declared goal.
PRUNE = [
    "Microsoft Excel - household budget.xlsx",
    "Microsoft Word - CV.docx",
    "Microsoft Word - Cover letter draft.docx",
    "Safari - Council tax account login",
    "Microsoft Excel - monthly expenses tracker.xlsx",
    "Notes - grocery list",
    "Notes - packing list for trip",
    "Microsoft Word - Flat viewing notes.docx",
    "Mail - Compose - Re flight booking confirmation",
]


def load_sets():
    """Normalise every dataset to {goal: {"focused": [...], "distraction": [...], "hard_negative": [...]}}."""
    out = []
    for name, path in EVAL_SETS:
        if not os.path.exists(path):
            print(f"  -- {name}: {os.path.relpath(path, ROOT)} not present, skipping")
            continue
        data = json.load(open(path))
        goals = []
        for g in data["goals"]:
            if "items" in g:  # human-labelled set: explicit per-item labels
                cats = {"focused": [], "distraction": [], "hard_negative": []}
                for it in g["items"]:
                    if it.get("label") == "on":
                        cats["focused"].append(it["window"])
                    elif it.get("type", "").startswith("hard"):
                        cats["hard_negative"].append(it["window"])
                    elif it.get("label") == "off":
                        cats["distraction"].append(it["window"])
                goals.append({"goal": g["goal"], **cats})
            else:
                goals.append({"goal": g["goal"], "domain": g.get("domain"),
                              "focused": g.get("focused", []),
                              "distraction": g.get("distraction", []),
                              "hard_negative": g.get("hard_negative", [])})
        out.append({"set": name, "path": os.path.relpath(path, ROOT), "goals": goals})
    return out


def pruned_worklike_file(original_path):
    """Write a pruned copy of the work-like bank to a temp file and return its path."""
    data = json.load(open(original_path))
    kept = [d for d in data.get("distraction", []) if d not in PRUNE]
    removed = [d for d in data.get("distraction", []) if d in PRUNE]
    fd, path = tempfile.mkstemp(suffix=".json", prefix="worklike_pruned_")
    with os.fdopen(fd, "w") as f:
        json.dump({"_about": "pruned copy generated by experiments/e2, not a repo file",
                   "distraction": kept}, f, indent=2)
    return path, kept, removed


def metrics(scores, threshold):
    """scores: {"focused": [...], "distraction": [...], "hard_negative": [...]}"""
    on = lambda xs: sum(1 for s in xs if s > threshold)
    f, d, h = scores["focused"], scores["distraction"], scores["hard_negative"]
    tp = on(f)
    fn = len(f) - tp
    fp = on(d) + on(h)
    tn = (len(d) - on(d)) + (len(h) - on(h))
    prec = tp / (tp + fp) if tp + fp else 0.0
    rec = tp / len(f) if f else 0.0
    f1 = 2 * prec * rec / (prec + rec) if prec + rec else 0.0
    return {
        "threshold": threshold,
        "focused_n": len(f), "false_alarms": fn,
        "false_alarm_rate": fn / len(f) if f else None,
        "hard_negative_n": len(h), "hard_negative_leaked": on(h),
        "hard_negative_leak_rate": on(h) / len(h) if h else None,
        "distraction_n": len(d), "distraction_leaked": on(d),
        "distraction_leak_rate": on(d) / len(d) if d else None,
        "tp": tp, "fn": fn, "fp": fp, "tn": tn,
        "accuracy": (tp + tn) / (len(f) + len(d) + len(h)),
        "precision": prec, "recall": rec, "f1": f1,
    }


def main():
    banner("E2  Calibration configurations on every labelled set")
    import engine as eng
    from classifier import WorkspaceClassifier

    sets = load_sets()
    if not sets:
        print("  !! no labelled evaluation sets found")
        return

    pruned_path, kept, removed = pruned_worklike_file(eng.WORK_LIKE_DISTRACTIONS_PATH)
    configs = {
        "fixed_0.01": None,  # special case, no calibration
        "generic": dict(work_like_path=None, templates_path=None),
        "generic_worklike": dict(work_like_path=eng.WORK_LIKE_DISTRACTIONS_PATH, templates_path=None),
        "generic_worklike_pruned": dict(work_like_path=pruned_path, templates_path=None),
        "generic_hardneg": dict(work_like_path=None, templates_path=eng.HARD_NEGATIVE_TEMPLATES_PATH),
        "worklike_pruned_hardneg": dict(work_like_path=pruned_path,
                                        templates_path=eng.HARD_NEGATIVE_TEMPLATES_PATH),
    }

    clf = WorkspaceClassifier()
    out = {
        "meta": run_meta(),
        "model": clf.model.__class__.__name__ if hasattr(clf, "model") else None,
        "configs": {k: ("no calibration, fixed 0.01" if v is None else
                        {kk: (os.path.relpath(vv, ROOT) if isinstance(vv, str) and vv.startswith(ROOT) else vv)
                         for kk, vv in v.items()}) for k, v in configs.items()},
        "pruning": {"rule": "a calibration example must never be something a user could declare as their goal",
                    "removed": removed, "kept": kept},
        "sets": [],
    }

    for s in sets:
        set_out = {"set": s["set"], "path": s["path"], "goals": []}
        for g in s["goals"]:
            texts = {c: list(g.get(c, [])) for c in ("focused", "distraction", "hard_negative")}
            flat = [t for c in texts for t in texts[c]]
            if not flat:
                continue
            raw = clf.score_batch(g["goal"], flat)
            scores, i = {}, 0
            for c in ("focused", "distraction", "hard_negative"):
                scores[c] = raw[i:i + len(texts[c])]
                i += len(texts[c])
            per_config = {}
            for name, kw in configs.items():
                thr = eng.DEFAULT_THRESHOLD if kw is None else eng.calibrate_threshold(clf, g["goal"], **kw)
                per_config[name] = metrics(scores, thr)
            set_out["goals"].append({
                "goal": g["goal"], "domain": g.get("domain"),
                "samples": {c: [{"window": t, "score": sc} for t, sc in zip(texts[c], scores[c])] for c in texts},
                "by_config": per_config,
            })
        out["sets"].append(set_out)

        print(f"\n--- {s['set']} ({len(set_out['goals'])} goals)")
        print(f"{'config':26s} {'leak hard':>10s} {'leak plain':>11s} {'false alarm':>12s} {'F1':>6s}")
        for name in configs:
            agg = {k: 0 for k in ("h", "hl", "d", "dl", "f", "fa")}
            f1s = []
            for gg in set_out["goals"]:
                m = gg["by_config"][name]
                agg["h"] += m["hard_negative_n"]; agg["hl"] += m["hard_negative_leaked"]
                agg["d"] += m["distraction_n"]; agg["dl"] += m["distraction_leaked"]
                agg["f"] += m["focused_n"]; agg["fa"] += m["false_alarms"]
                f1s.append(m["f1"])
            hl = agg["hl"] / agg["h"] if agg["h"] else float("nan")
            dl = agg["dl"] / agg["d"] if agg["d"] else float("nan")
            fa = agg["fa"] / agg["f"] if agg["f"] else float("nan")
            print(f"{name:26s} {hl:9.1%} {dl:10.1%} {fa:11.1%} {sum(f1s)/len(f1s):6.2f}")
            set_out.setdefault("pooled", {})[name] = {
                "hard_negative_leak_rate": hl, "distraction_leak_rate": dl,
                "false_alarm_rate": fa, "mean_goal_f1": sum(f1s) / len(f1s),
                "counts": agg,
            }

    save_json("e2_calibration.json", out)
    os.unlink(pruned_path)


if __name__ == "__main__":
    main()
